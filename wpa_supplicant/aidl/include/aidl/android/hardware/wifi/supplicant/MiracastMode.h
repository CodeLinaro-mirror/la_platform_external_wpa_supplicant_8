namespace aidl {
namespace android {
namespace hardware {
namespace wifi {
namespace supplicant {
enum class MiracastMode : int8_t {
  DISABLED = 0,
  SOURCE = 1,
  SINK = 2,
};

}  // namespace supplicant
}  // namespace wifi
}  // namespace hardware
}  // namespace android
}  // namespace aidl
namespace aidl {
namespace android {
namespace hardware {
namespace wifi {
namespace supplicant {
[[nodiscard]] static inline std::string toString(MiracastMode val) {
  switch(val) {
  case MiracastMode::DISABLED:
    return "DISABLED";
  case MiracastMode::SOURCE:
    return "SOURCE";
  case MiracastMode::SINK:
    return "SINK";
  default:
    return std::to_string(static_cast<int8_t>(val));
  }
}
}  // namespace supplicant
}  // namespace wifi
}  // namespace hardware
}  // namespace android
}  // namespace aidl
